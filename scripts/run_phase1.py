def table(header, rows):
    w("| " + " | ".join(header) + " |")
    w("|" + "---|" * len(header))
    for r in rows:
        w("| " + " | ".join(r) + " |")
    w("")


w("# Phase 1 results: analytic Heston pricer\n")
w(f"Generated by `scripts/run_phase1.py` (Python {platform.python_version()}, numpy {np.__version__}).\n")

# 1. literature benchmark
w("## 1. Literature benchmark (Fang & Oosterlee 2008)\n")
w(f"Parameters: {FO_PARAMS.as_dict()}, S0 = K = 100, T = 1, r = q = 0. "
  f"Feller ratio = {FO_PARAMS.feller_ratio:.3f} (violated).\n")
rows = []
for name, f in [("Lewis + composite GL (primary)", heston_price), ("Lewis + adaptive quad", heston_price_quad),
                ("Gil-Pelaez two-probability (quad)", heston_price_gil_pelaez)]:
    v = float(f(100, 100, 1.0, 0.0, 0.0, FO_PARAMS))
    rows.append([name, f"{v:.10f}", f"{v - FO_REFERENCE_CALL:+.2e}"])


def mp_reference(p: HestonParams, T: float = 1.0, dps: int = 30):
    """Lewis integral at `dps` significant digits with mpmath (little-trap CF)."""
    import mpmath as mp
    mp.mp.dps = dps
    v0, k, th, s, rho = (mp.mpf(repr(x)) for x in (p.v0, p.kappa, p.theta, p.sigma, p.rho))

    def phi(u):
        iu = 1j * u
        b = k - rho * s * iu
        d = mp.sqrt(b * b + s**2 * (iu + u * u))
        g = (b - d) / (b + d)
        e = mp.exp(-d * T)
        C = k * th / s**2 * ((b - d) * T - 2 * mp.log((1 - g * e) / (1 - g)))
        D = (b - d) / s**2 * (1 - e) / (1 - g * e)
        return mp.exp(C + D * v0)

    integral = mp.quad(lambda u: mp.re(phi(u - 0.5j)) / (u * u + mp.mpf(1) / 4), [0, 1, 5, 20, 50, 100, 200, mp.inf])
    return 100 - 100 / mp.pi * integral


try:
    hp = mp_reference(FO_PARAMS)
    rows.append(["Lewis, mpmath 30 digits", f"{float(hp):.10f}", f"{float(hp) - FO_REFERENCE_CALL:+.2e}"])
    hp_note = (f"The 30-digit value is {str(hp)[:18]}. All three double-precision methods agree with it to "
               f"{abs(float(heston_price(100, 100, 1.0, 0.0, 0.0, FO_PARAMS)) - float(hp)):.1e}; the published "
               "9-decimal figure is 1.6e-8 higher. The mpmath row uses the same Lewis/little-trap formula; the Gil-Pelaez row is an "
               "independent formula and agrees too, so we treat the last published digit as not reproducible.\n")
except ImportError:
    hp_note = "(mpmath not installed: high-precision row skipped.)\n"
table(["Method", "Call price", "vs published 5.785155450"], rows)
w(hp_note)

# 2. accuracy vs independent formula over random cases
w("## 2. Primary pricer vs independent Gil-Pelaez formula (random cases)\n")
cases = random_cases(400, seed=2024)
t0 = time.perf_counter()
errs = np.array([abs(heston_price(100, K, T, 0.03, 0.01, p) - heston_price_gil_pelaez(100, K, T, 0.03, 0.01, p))
                 for p, T, K in cases])
w(f"{len(cases)} random cases: v0, theta in [0.005, 0.2], kappa in [0.2, 6], sigma in [0.05, 1.5], "
  f"rho in [-0.95, 0.5], T log-uniform in [1 week, 5y], ln(K/S) in +-0.6 sqrt(T); r = 3%, q = 1%.\n")
table(["Statistic", "Absolute price difference"],
      [["median", f"{np.median(errs):.2e}"], ["99th pct", f"{np.quantile(errs, 0.99):.2e}"],
       ["max", f"{errs.max():.2e}"]])

# 3. timing
w("## 3. Speed (single CPU core, wall clock)\n")
p0 = HestonParams(0.04, 2.0, 0.04, 0.5, -0.7)
K50 = np.linspace(60, 140, 50)
rows = []
for T in [1 / 52, 0.25, 1.0, 5.0]:
    U = truncation_bound(T, p0)
    n = _composite_gl(U, 20.0, 24)[0].size
    heston_price(100, K50, T, 0.03, 0.01, p0)
    reps = 200
    t0 = time.perf_counter()
    for _ in range(reps):
        heston_price(100, K50, T, 0.03, 0.01, p0)
    ms = (time.perf_counter() - t0) / reps * 1e3
    t0 = time.perf_counter()
    heston_price_quad(100, K50, T, 0.03, 0.01, p0)
    qms = (time.perf_counter() - t0) * 1e3
    rows.append([f"{T:.4f}", f"{U:.0f}", str(n), f"{ms:.2f}", f"{qms:.0f}"])
table(["T", "Truncation U", "CF nodes", "GL: ms / 50 strikes", "quad: ms / 50 strikes"], rows)

# 4. BS limit
w("## 4. Black-Scholes limit (sigma -> 0)\n")
w("With sigma -> 0 the variance is deterministic, E[v_t] = theta + (v0 - theta) e^{-kappa t}, so the "
  "Heston price must converge to BS with variance equal to the time-average of E[v_t]. "
  "v0 = 0.06, kappa = 1.5, theta = 0.03, T = 0.75, K = 80/100/120.\n")
rows = []
K3 = np.array([80.0, 100.0, 120.0])
for rho in [0.0, -0.7]:
    for s in [1e-1, 1e-2, 1e-3]:
        p = HestonParams(0.06, 1.5, 0.03, s, rho)
        bs = bs_price(100, K3, 0.75, 0.03, 0.01, np.sqrt(p.expected_avg_variance(0.75)))
        e = np.max(np.abs(heston_price(100, K3, 0.75, 0.03, 0.01, p) - bs))
        rows.append([f"{rho}", f"{s:g}", f"{e:.2e}"])
table(["rho", "sigma", "max abs diff vs BS"], rows)
w("Observed: error falls ~100x per 10x smaller sigma when rho = 0 (second order) and ~10x when "
  "rho != 0 (first-order correlation/vanna term), as the small-vol-of-vol expansion predicts.\n")

# 5. MC
w("## 5. Independent Monte Carlo check (full-truncation Euler)\n")
pm = HestonParams(0.04, 2.0, 0.04, 0.3, -0.7)
w(f"Parameters {pm.as_dict()} (Feller ratio {pm.feller_ratio:.2f}), T = 1, r = 3%, q = 1%, "
  "200,000 paths (antithetic), 250 steps. Phase 2 replaces this with Andersen QE.\n")
rows = []
for K, kind in [(80.0, "call"), (100.0, "call"), (120.0, "call"), (90.0, "put")]:
    mc = price_euler_mc(100, K, 1.0, 0.03, 0.01, pm, kind, n_paths=200_000, n_steps=250, seed=7)
    ex = float(heston_price(100, K, 1.0, 0.03, 0.01, pm, kind))
    rows.append([f"{kind} {K:.0f}", f"{ex:.4f}", f"{mc.price:.4f}", f"{mc.std_error:.4f}",
                 f"{(mc.price - ex) / mc.std_error:+.2f}"])
table(["Option", "Analytic", "MC", "MC s.e.", "z"], rows)

# 6. branch cut
w("## 6. Why the little-trap characteristic function\n")
pb = HestonParams(0.04, 2.0, 0.04, 0.6, -0.8)
w(f"Parameters {pb.as_dict()}, S = F = 100 (r = q = 0). Same Lewis integral and nodes, only the CF form "
  "changes. With numpy's principal-branch complex log, the original Heston (1993) form jumps branches "
  "along the integration path; nodes where it overflows (e^{+dT}) are dropped, which is what a naive "
  "implementation would effectively do.\n")
rows = []
Kb = np.array([80.0, 100.0, 120.0])
for T in [0.5, 1.0, 2.0, 5.0, 10.0]:
    U = truncation_bound(T, pb)
    u, wu = _composite_gl(U, 20.0, 24)
    res = []
    for cf in (cf_little_trap, cf_heston1993):
        with np.errstate(all="ignore"):
            phi = cf(u - 0.5j, T, pb)
        ok = np.isfinite(phi)
        val = (np.exp(1j * np.outer(np.log(100 / Kb), u[ok])) * phi[ok] / (u[ok] ** 2 + 0.25)).real @ wu[ok]
        res.append(100 - np.sqrt(100 * Kb) / np.pi * val)
    rows.append([f"{T:g}"] + [f"{a:.4f} / {b:.4f}" for a, b in zip(*res)])
table(["T", "K=80 trap / 1993", "K=100 trap / 1993", "K=120 trap / 1993"], rows)

uu = np.linspace(0, 20, 4001)
with np.errstate(all="ignore"):
    bad = cf_heston1993(uu - 0.5j, 5.0, pb)
good = cf_little_trap(uu - 0.5j, 5.0, pb)
fig, ax = plt.subplots(figsize=(7, 3.6))
ax.plot(uu, good.real, label="little trap (Albrecher et al. 2007)", lw=2)
ax.plot(uu, bad.real, "--", label="original Heston (1993), principal log", lw=1.4)
ax.set_xlabel("u")
ax.set_ylabel(r"Re $\phi(u - i/2)$")
ax.set_title("T = 5y: branch-cut discontinuity of the original form")
ax.legend()
fig.tight_layout()
fig.savefig(FIG / "phase1_branch_cut.png", dpi=150)
plt.close(fig)
w("![branch cut](figures/phase1_branch_cut.png)\n")

# 7. smile
w("## 7. Implied-volatility smile produced by the model\n")
fig, ax = plt.subplots(figsize=(7, 3.6))
Ks = np.linspace(70, 140, 71)
for T in [0.1, 0.5, 1.0, 2.0]:
    F = 100 * np.exp(0.02 * T)
    kind = np.where(Ks < F, "put", "call")
    iv = implied_vol(heston_price(100, Ks, T, 0.03, 0.01, p0, kind), 100, Ks, T, 0.03, 0.01, kind)
    ax.plot(np.log(Ks / F), iv, label=f"T = {T}")
ax.set_xlabel("log-moneyness ln(K/F)")
ax.set_ylabel("implied vol")
ax.set_title(f"Heston smile, {p0.as_dict()}", fontsize=8)
ax.legend()
fig.tight_layout()
fig.savefig(FIG / "phase1_smile.png", dpi=150)
plt.close(fig)
w("Negative rho produces the equity-style downward skew; it flattens with maturity.\n")
w("![smile](figures/phase1_smile.png)\n")

