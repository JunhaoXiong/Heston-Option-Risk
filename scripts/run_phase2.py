"""Phase 2 experiment: Andersen QE vs full-truncation Euler against the analytic price.

Writes reports/phase2_results.md, reports/phase2_bias.csv and figures in reports/figures/.
Every number in the report is computed here. Runtime: several minutes on one core.
Run:  python scripts/run_phase2.py            (full: 1,000,000 paths per point)
      python scripts/run_phase2.py --quick    (100,000 paths, for a smoke test)
"""
from __future__ import annotations

import argparse
import csv
import platform
import sys
import time
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from heston_risk import HestonParams, heston_price  # noqa: E402
from heston_risk.mc.simulate import price_mc  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--quick", action="store_true")
args = ap.parse_args()
N_PATHS = 100_000 if args.quick else 1_000_000
OUT = ROOT / "reports"
FIG = OUT / "figures"
FIG.mkdir(parents=True, exist_ok=True)
S0, R, Q = 100.0, 0.0, 0.0

CASES = {
    "A (mild, Feller ok)": (HestonParams(0.04, 2.0, 0.04, 0.3, -0.7), 1.0, [80.0, 100.0, 120.0]),
    "B (Fang-Oosterlee)": (HestonParams(0.0175, 1.5768, 0.0398, 0.5751, -0.5711), 1.0, [80.0, 100.0, 120.0]),
    "I (Andersen)": (HestonParams(0.04, 0.5, 0.04, 1.0, -0.9), 10.0, [70.0, 100.0, 140.0]),
    "II (Andersen)": (HestonParams(0.04, 0.3, 0.04, 0.9, -0.5), 15.0, [70.0, 100.0, 140.0]),
    "III (Andersen)": (HestonParams(0.09, 1.0, 0.09, 1.0, -0.3), 5.0, [70.0, 100.0, 140.0]),
}
DTS = [1.0, 1 / 2, 1 / 4, 1 / 8, 1 / 16, 1 / 32]
SCHEMES = ["qe", "euler"]
DT_LABEL = {1.0: "1", 0.5: "1/2", 0.25: "1/4", 0.125: "1/8", 0.0625: "1/16", 0.03125: "1/32"}

lines: list[str] = []
w = lines.append


def table(header, rows):
    w("| " + " | ".join(header) + " |")
    w("|" + "---|" * len(header))
    for r in rows:
        w("| " + " | ".join(r) + " |")
    w("")


rows_csv = []
t_start = time.perf_counter()
for ci, (name, (p, T, Ks)) in enumerate(CASES.items()):
    exact = heston_price(S0, Ks, T, R, Q, p)
    for si, scheme in enumerate(SCHEMES):
        for di, dt in enumerate(DTS):
            n_steps = max(1, int(round(T / dt)))
            seed = 1000 * ci + 100 * si + di
            m = price_mc(S0, Ks, T, R, Q, p, "call", n_paths=N_PATHS, n_steps=n_steps, scheme=scheme,
                         seed=seed, batch_paths=250_000)
            for K, ex, px, se in zip(Ks, exact, m.price, m.std_error):
                rows_csv.append(dict(case=name, scheme=scheme, dt=dt, n_steps=n_steps, K=K, exact=ex, mc=px,
                                     bias=px - ex, se=se, z=(px - ex) / se, seconds=m.seconds,
                                     exp_branch_frac=(m.stats.n_exponential_branch / m.stats.n_variance_draws
                                                      if scheme == "qe" else np.nan),
                                     neg_var_frac=(m.stats.n_negative_variance / m.stats.n_variance_draws
                                                   if scheme == "euler" else np.nan),
                                     mart_fallback=m.stats.n_martingale_fallback))
            print(f"{name:22s} {scheme:5s} dt={DT_LABEL[dt]:>4s} {m.seconds:6.1f}s "
                  f"bias={np.round(m.price - exact, 4)} se={np.round(m.std_error, 4)}", flush=True)
total_secs = time.perf_counter() - t_start

with open(OUT / "phase2_bias.csv", "w", newline="") as f:
    wr = csv.DictWriter(f, fieldnames=list(rows_csv[0]))
    wr.writeheader()
    wr.writerows(rows_csv)


def sel(case, scheme, K=None, dt=None):
    return [r for r in rows_csv if r["case"] == case and r["scheme"] == scheme
            and (K is None or r["K"] == K) and (dt is None or r["dt"] == dt)]


w("# Phase 2 results: Monte Carlo (Andersen QE vs full-truncation Euler)\n")
w(f"Generated by `scripts/run_phase2.py` (Python {platform.python_version()}, numpy {np.__version__}); "
  f"{N_PATHS:,} paths per point (antithetic pairs), S0 = 100, r = q = 0. Total runtime {total_secs / 60:.1f} min "
  "on one core. Truth = Phase 1 analytic price. Bias = MC - analytic; s.e. from antithetic-pair averages; "
  "'*' marks |bias| > 2 s.e. (statistically significant at ~5%). Raw numbers: `reports/phase2_bias.csv`.\n")

w("## 1. Test cases\n")
rows = []
for name, (p, T, Ks) in CASES.items():
    rows.append([name, f"{p.v0}", f"{p.kappa}", f"{p.theta}", f"{p.sigma}", f"{p.rho}", f"{T:g}",
                 f"{p.feller_ratio:.3f}", " / ".join(f"{k:g}" for k in Ks),
                 " / ".join(f"{e:.4f}" for e in heston_price(S0, Ks, T, R, Q, p))])
table(["Case", "v0", "kappa", "theta", "sigma", "rho", "T", "Feller ratio", "Strikes", "Analytic calls"], rows)

w("## 2. Bias by time step\n")
for name, (p, T, Ks) in CASES.items():
    w(f"### Case {name}\n")
    hdr = ["dt"] + [f"{s.upper()} K={k:g}" for s in SCHEMES for k in Ks]
    rows = []
    for dt in DTS:
        r = [DT_LABEL[dt]]
        for s in SCHEMES:
            for k in Ks:
                x = sel(name, s, k, dt)[0]
                star = "*" if abs(x["z"]) > 2 else ""
                r.append(f"{x['bias']:+.4f} ({x['se']:.4f}){star}")
        rows.append(r)
    table(hdr, rows)

w("## 3. Summary: coarsest time step without significant bias\n")
w("For each case and scheme: the coarsest dt at which **no** strike shows a significant bias "
  "(|bias| <= 2 s.e. at this path count), and the worst |bias| at dt = 1/8.\n")
rows = []
for name, (p, T, Ks) in CASES.items():
    r = [name]
    for s in SCHEMES:
        ok = [dt for dt in DTS if all(abs(x["z"]) <= 2 for x in sel(name, s, dt=dt))]
        coarsest = None
        for dt in DTS:  # coarsest dt such that it and all finer dts are clean
            if all(d in ok for d in DTS if d <= dt):
                coarsest = dt
                break
        worst = max(abs(x["bias"]) for x in sel(name, s, dt=0.125))
        r += [DT_LABEL[coarsest] if coarsest else "none", f"{worst:.4f}"]
    rows.append(r)
table(["Case", "QE: clean from dt", "QE: max abs bias @1/8", "Euler: clean from dt", "Euler: max abs bias @1/8"], rows)

w("## 4. Euler convergence order\n")
w("Least-squares slope of log|bias| on log dt over the points where the Euler bias is significant "
  "(ATM). First-order weak convergence would give a slope of about 1.\n")
rows = []
for name, (p, T, Ks) in CASES.items():
    pts = [(x["dt"], abs(x["bias"])) for x in sel(name, "euler", 100.0) if abs(x["z"]) > 2]
    if len(pts) >= 3:
        d, b = np.log(np.array(pts)).T
        slope = np.polyfit(d, b, 1)[0]
        rows.append([name, str(len(pts)), f"{slope:.2f}"])
    else:
        rows.append([name, str(len(pts)), "n/a (bias not significant at enough dt)"])
table(["Case", "significant points", "slope"], rows)

w("## 5. Accuracy per unit of CPU time (ATM)\n")
w("Each point is one run of the table above: x = wall-clock seconds for all paths, "
  "y = RMSE estimate sqrt(bias^2 + s.e.^2). Lower-left is better.\n")
fig, axes = plt.subplots(1, len(CASES), figsize=(16, 3.6), sharey=False)
for ax, (name, (p, T, Ks)) in zip(axes, CASES.items()):
    for s, mk in zip(SCHEMES, ["o-", "s--"]):
        xs = [x["seconds"] for x in sel(name, s, 100.0)]
        ys = [np.hypot(x["bias"], x["se"]) for x in sel(name, s, 100.0)]
        ax.loglog(xs, ys, mk, label=s.upper())
    ax.set_title(name, fontsize=9)
    ax.set_xlabel("seconds")
axes[0].set_ylabel("RMSE (ATM call)")
axes[0].legend()
fig.tight_layout()
fig.savefig(FIG / "phase2_efficiency.png", dpi=150)
plt.close(fig)
w("![efficiency](figures/phase2_efficiency.png)\n")

fig, axes = plt.subplots(1, len(CASES), figsize=(16, 3.6))
for ax, (name, (p, T, Ks)) in zip(axes, CASES.items()):
    for s, c in zip(SCHEMES, ["C0", "C3"]):
        xs = sel(name, s, 100.0)
        ax.errorbar([x["dt"] for x in xs], [x["bias"] for x in xs], yerr=[2 * x["se"] for x in xs],
                    fmt="o-", color=c, capsize=3, label=s.upper())
    ax.axhline(0, color="k", lw=0.8)
    ax.set_xscale("log", base=2)
    ax.set_title(name, fontsize=9)
    ax.set_xlabel("dt (years)")
axes[0].set_ylabel("bias of ATM call (+-2 s.e.)")
axes[0].legend()
fig.tight_layout()
fig.savefig(FIG / "phase2_bias.png", dpi=150)
plt.close(fig)
w("## 6. Bias of the ATM call against dt\n")
w("![bias](figures/phase2_bias.png)\n")

w("## 7. Scheme diagnostics\n")
rows = []
for name in CASES:
    q = sel(name, "qe", 100.0, 0.125)[0]
    e = sel(name, "euler", 100.0, 0.125)[0]
    fb = sum(x["mart_fallback"] for x in sel(name, "qe", 100.0))
    rows.append([name, f"{q['exp_branch_frac']:.1%}", str(fb), f"{e['neg_var_frac']:.1%}"])
table(["Case", "QE: share of exponential-branch draws (dt=1/8)", "QE: martingale-correction fallbacks (all dt)",
       "Euler: share of steps with v < 0 before truncation (dt=1/8)"], rows)

# variance reduction
w("## 8. Variance reduction (dt = 1/8, ATM call)\n")
w("Same number of payoff evaluations in each row. Variance reduction factor = (plain s.e. / s.e.)^2; "
  "time-adjusted factor divides by the relative CPU time.\n")
rows = []
for name in ["A (mild, Feller ok)", "I (Andersen)"]:
    p, T, _ = CASES[name]
    n_steps = int(round(T / 0.125))
    nvr = N_PATHS // 2
    runs = {
        "plain": price_mc(S0, [100.0], T, R, Q, p, n_paths=nvr, n_steps=n_steps, seed=77, antithetic=False),
        "antithetic": price_mc(S0, [100.0], T, R, Q, p, n_paths=nvr, n_steps=n_steps, seed=77),
        "antithetic + control variate": price_mc(S0, [100.0], T, R, Q, p, n_paths=nvr, n_steps=n_steps,
                                                 seed=77, control_variate=True),
    }
    base = runs["plain"]
    for lab, m in runs.items():
        vrf = (base.std_error[0] / m.std_error[0]) ** 2
        rows.append([name, lab, f"{m.price[0]:.4f}", f"{m.std_error[0]:.4f}", f"{vrf:.2f}",
                     f"{vrf * base.seconds / m.seconds:.2f}"])
table(["Case", "Estimator", "Price", "s.e.", "VR factor", "time-adjusted VR"], rows)

(OUT / "phase2_results.md").write_text("\n".join(lines))
print("\n".join(lines))
