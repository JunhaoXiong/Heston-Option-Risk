"""Phase 3: calibrate Heston to the SPY implied-volatility surface of 2026-11-20 (close).

Writes reports/phase3_results.md, reports/phase3_quotes.csv, reports/phase3_params.json
and figures in reports/figures/. Every number in the report is computed here.
Run:  python scripts/run_phase3.py   (several minutes; --starts N to change the multi-start count)
"""
from __future__ import annotations

import argparse
import json
import platform
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from heston_risk.calibration.american import de_americanize, early_exercise_premium  # noqa: E402
from heston_risk.calibration.calibrate import NAMES, calibrate, fit_black_scholes, fit_report  # noqa: E402
from heston_risk.calibration.data import (build_quotes, implied_forwards, load_snapshot,  # noqa: E402
                                          rate_from_irx)
from heston_risk import heston_price, implied_vol  # noqa: E402
from heston_risk.bs import bs_vega  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--starts", type=int, default=10)
args = ap.parse_args()

DATA = ROOT / "data" / "spy_2026-11-20"
OUT = ROOT / "reports"
FIG = OUT / "figures"
FIG.mkdir(parents=True, exist_ok=True)
lines: list[str] = []
w = lines.append


def table(header, rows):
    w("| " + " | ".join(header) + " |")
    w("|" + "---|" * len(header))
    for r in rows:
        w("| " + " | ".join(str(c) for c in r) + " |")
    w("")


raw, irx, hist, meta = load_snapshot(DATA)
irx_pct = float(irx.Close.iloc[-1])
r = rate_from_irx(irx_pct)
asof = raw.lastTradeDate.max()
spy_close = float(hist.Close.iloc[-1])
fwd = implied_forwards(raw, r, asof, spot_ref=spy_close)
# after-hours spot implied by the 1-week forward (no SPY dividend before mid-December)
wk = fwd.loc[fwd["T"] >= 5 / 365].iloc[0]
spot_ah = float(wk.F * np.exp(-r * wk["T"]))
fwd["q_implied"] = r - np.log(fwd.F / spot_ah) / fwd["T"]
quotes, funnel = build_quotes(raw, fwd, r)

w("# Phase 3 results: Heston calibrated to the SPY surface (2026-11-20 close)\n")
w(f"Generated by `scripts/run_phase3.py` (Python {platform.python_version()}, numpy {np.__version__}). "
  f"Data: `data/spy_2026-11-20/` (Yahoo Finance via yfinance, fetched {meta['fetched_utc'][:16]} UTC, "
  f"sha256-verified on load).\n")

w("## 1. Market inputs\n")
table(["Item", "Value"], [
    ["Last option quote time (UTC)", str(asof)],
    ["SPY official close", f"{spy_close:.2f}"],
    ["SPY after-hours level implied by the 1-week forward", f"{spot_ah:.2f}"],
    ["^IRX (13-week T-bill discount yield)", f"{irx_pct:.3f}%"],
    ["Flat continuous rate r used for discounting", f"{r:.4%}"],
])
w("The option quotes end about 15 minutes after the equity close and SPY moved after hours, "
  "which is why forwards are implied from put-call parity instead of being built from the close.\n")

w("## 2. Implied forwards (put-call parity, median over near-the-money strikes)\n")
table(["Expiry", "T (y)", "F", "strikes used", "IQR of estimates", "implied q"],
      [[e, f"{T:.3f}", f"{F:.2f}", n, f"{iqr:.2f}", f"{qq:.2%}"]
       for e, T, F, n, iqr, qq in fwd[["expiry", "T", "F", "n_strikes", "iqr", "q_implied"]].itertuples(index=False)])
w("Short expiries carry large positive/negative implied q because the dollar dividend (ex-date mid-December) "
  "is spread over a tiny T; only the forward itself enters the pricing, so this is harmless. "
  "One expiry (2027-03-31) has a wide IQR from a few bad quotes; the median is unaffected.\n")

w("## 3. Quote filters\n")
table(["Step", "Quotes left"], funnel.values.tolist())
w(f"Final set: {len(quotes)} out-of-the-money quotes over {quotes.expiry.nunique()} expiries, "
  f"T from {quotes['T'].min() * 365:.0f} days to {quotes['T'].max():.2f} years, market IV "
  f"{quotes.iv.min():.1%} to {quotes.iv.max():.1%}.\n")

# American premium
w("## 4. Early-exercise premium of the quotes used (CRR tree, 300 steps)\n")
prem, prem_rel, prem_vol = [], [], []
for row in quotes.itertuples(index=False):
    qq = r - np.log(row.F / spot_ah) / row.T
    pr, _ = early_exercise_premium(spot_ah, row.strike, row.T, r, qq, row.iv, row.kind, n=300)
    prem.append(pr)
    prem_rel.append(pr / row.mid)
    prem_vol.append(pr / row.vega)
quotes["ee_premium"] = prem
quotes["ee_premium_vol"] = prem_vol
pv = np.array(prem_vol) * 100
pr_rel = np.array(prem_rel) * 100
quotes["bucket"] = pd.cut(quotes["T"], [0, 30 / 365, 90 / 365, 0.5, 1.0, 3.0],
                          labels=["7-30d", "1-3m", "3-6m", "6-12m", "1-2.2y"])
rows = []
for (kind, b), d in quotes.groupby(["kind", "bucket"], observed=True):
    v = d.ee_premium_vol.values * 100
    rows.append([kind, b, len(d), f"{np.median(v):.3f}", f"{np.percentile(v, 90):.3f}", f"{v.max():.3f}"])
table(["Type", "Maturity", "Quotes", "median (vol pts)", "90th pct", "max"], rows)
w("Premium measured at each quote's European-inverted IV. Calls carry essentially no premium (low dividend "
  "yield). **Puts do, and it grows with maturity**: because r (4.2%) exceeds q (about 1%), the forward is far "
  "above spot for long maturities, so a put that is out of the money against the forward can be in the money "
  "against spot, and early exercise to earn interest on the strike is valuable. For 1-2 year puts the "
  "median premium is comparable to the calibration error below, so ignoring it is **not** negligible there. "
  "Section 6 therefore also calibrates to de-Americanised quotes.\n")

w("### De-Americanisation\n")
w("For every quote with a positive premium: solve the CRR American volatility sigma_A that reproduces the mid, "
  "then subtract the tree's early-exercise premium at sigma_A (American minus European on the same tree, so "
  "tree error cancels) and re-invert the European IV. Bid and ask are shifted by the same premium.\n")
eu_mid = quotes.mid.values.copy()
for i, row in enumerate(quotes.itertuples(index=False)):
    if row.ee_premium > 1e-6:
        qq = r - np.log(row.F / spot_ah) / row.T
        e_px, _ = de_americanize(row.mid, spot_ah, row.strike, row.T, r, qq, row.kind, row.iv, n=300)
        if np.isfinite(e_px):
            eu_mid[i] = e_px
quotes_eu = quotes.copy()
shift = quotes.mid.values - eu_mid
quotes_eu["mid"], quotes_eu["bid"], quotes_eu["ask"] = eu_mid, quotes.bid - shift, quotes.ask - shift
kinds = quotes.kind.values.astype(str)
quotes_eu["iv"] = implied_vol(eu_mid, quotes.S_eff.values, quotes.strike.values, quotes["T"].values, r, 0.0, kinds)
quotes_eu["iv_bid"] = implied_vol(quotes_eu.bid.values, quotes.S_eff.values, quotes.strike.values,
                                  quotes["T"].values, r, 0.0, kinds)
quotes_eu["iv_ask"] = implied_vol(quotes_eu.ask.values, quotes.S_eff.values, quotes.strike.values,
                                  quotes["T"].values, r, 0.0, kinds)
ok_eu = np.isfinite(quotes_eu.iv.values)
quotes_eu["vega"] = bs_vega(quotes.S_eff.values, quotes.strike.values, quotes["T"].values, r, 0.0,
                            np.where(ok_eu, quotes_eu.iv.values, quotes.iv.values))
d_iv = (quotes.iv - quotes_eu.iv)[ok_eu] * 100
w(f"{int((shift > 1e-6).sum())} quotes adjusted; {int((~ok_eu).sum())} could not be re-inverted and are dropped "
  f"from the de-Americanised set. IV reduction: median {np.median(d_iv[shift[ok_eu] > 1e-6]):.3f}, "
  f"max {d_iv.max():.3f} vol points.\n")

# split
rng = np.random.default_rng(42)
test_mask = np.zeros(len(quotes), dtype=bool)
for e, idx in quotes.groupby("expiry").indices.items():
    n_test = int(round(0.2 * len(idx)))
    test_mask[rng.choice(idx, n_test, replace=False)] = True
train, test = quotes[~test_mask].reset_index(drop=True), quotes[test_mask].reset_index(drop=True)
train_eu = quotes_eu[~test_mask & ok_eu].reset_index(drop=True)
test_eu = quotes_eu[test_mask & ok_eu].reset_index(drop=True)

res_free = calibrate(train, r, n_starts=args.starts, seed=0, feller=False)
res_fel = calibrate(train, r, n_starts=args.starts, seed=0, feller=True)
res_eu = calibrate(train_eu, r, n_starts=args.starts, seed=0, feller=False)
FITS = [("Unconstrained, raw quotes", res_free, train, test),
        ("Feller-constrained, raw quotes", res_fel, train, test),
        ("Unconstrained, de-Americanised", res_eu, train_eu, test_eu)]

w("## 5. Calibrated parameters (training set, 80% of quotes stratified by expiry)\n")
rows = []
for lab, res, _, _ in FITS:
    p = res.params
    rows.append([lab, f"{p.v0:.4f}", f"{p.kappa:.3f}", f"{p.theta:.4f}", f"{p.sigma:.3f}", f"{p.rho:.3f}",
                 f"{p.feller_ratio:.3f}", f"{np.sqrt(p.v0):.1%}", f"{np.sqrt(p.theta):.1%}",
                 f"{res.seconds:.0f}"])
table(["Fit", "v0", "kappa", "theta", "sigma", "rho", "Feller ratio", "sqrt(v0)", "sqrt(theta)",
       f"seconds ({args.starts} starts)"], rows)

pf, pe = res_free.params, res_eu.params
w(f"De-Americanising the put quotes moves the unconstrained fit only slightly: theta {pf.theta:.4f} -> {pe.theta:.4f}, "
  f"kappa {pf.kappa:.2f} -> {pe.kappa:.2f}, sigma {pf.sigma:.3f} -> {pe.sigma:.3f}, rho {pf.rho:.3f} -> {pe.rho:.3f}. "
  f"The Feller-constrained fit runs into the rho = -0.999 bound: with sigma^2 <= 2 kappa theta it cannot produce "
  f"enough skew through vol-of-vol, so it pushes correlation to the limit instead.\n")
w("**Parameters carried into Phases 4-5: the unconstrained raw-quote fit** (as agreed; the de-Americanised fit is "
  "a sensitivity).\n")

w("## 6. Fit quality (IV errors in vol points, i.e. 1.00 = 1% vol)\n")
bs_vol = fit_black_scholes(train)
rows = []
fits = {}
for lab, res, tr, te in FITS:
    for setname, d in [("train", tr), ("test", te)]:
        f = fit_report(d, res.params, r)
        fits[(lab, setname)] = f
        e = f.iv_err.dropna().values * 100
        vw = (f.model - f.mid) / f.vega * 100
        rows.append([lab, setname, len(f), f"{len(e)}", f"{np.sqrt(np.mean(e ** 2)):.3f}",
                     f"{np.sqrt(np.mean(vw ** 2)):.3f}", f"{np.mean(np.abs(e)):.3f}",
                     f"{np.max(np.abs(e)):.3f}", f"{f.in_spread.mean():.1%}"])
for setname, d in [("train", train), ("test", test)]:
    e = (bs_vol - d.iv.values) * 100  # raw quotes
    bsp = d.copy()
    rows.append(["Black-Scholes, one vol " + f"({bs_vol:.2%})", setname, len(d), len(d),
                 f"{np.sqrt(np.mean(e ** 2)):.3f}", "n/a", f"{np.mean(np.abs(e)):.3f}", f"{np.max(np.abs(e)):.3f}",
                 "n/a"])
table(["Model", "Set", "Quotes", "model IV invertible", "IV RMSE", "vega-weighted price RMSE",
       "IV MAE", "max |IV err|", "model price inside bid-ask"], rows)
w("IV statistics use the quotes whose model price can be inverted to an implied vol; a model price "
  "outside the no-arbitrage bounds (for example below intrinsic value) cannot, and is counted in the "
  "'invertible' column. The vega-weighted price RMSE (the calibration objective) uses all quotes.\n")
spread_vol = ((quotes.iv_ask - quotes.iv_bid) * 100)
w(f"For scale: the median quoted bid-ask spread is {np.nanmedian(spread_vol):.2f} vol points "
  f"(mean {np.nanmean(spread_vol):.2f}).\n")

w("## 7. Errors by maturity (unconstrained fit, raw quotes, all quotes)\n")
allfit = fit_report(quotes, res_free.params, r)
allfit["bucket"] = pd.cut(allfit["T"], [0, 30 / 365, 90 / 365, 0.5, 1.0, 3.0],
                          labels=["7-30d", "1-3m", "3-6m", "6-12m", "1-2.2y"])
rows = []
for b, d in allfit.groupby("bucket", observed=True):
    e = d.iv_err.dropna().values * 100
    put = d[d.k < -0.02].iv_err.mean() * 100
    call = d[d.k > 0.02].iv_err.mean() * 100
    rows.append([b, len(d), f"{np.sqrt(np.mean(e ** 2)):.3f}", f"{put:+.3f}", f"{call:+.3f}", f"{d.in_spread.mean():.1%}"])
table(["Maturity", "Quotes", "IV RMSE", "mean err, puts (k<-0.02)", "mean err, calls (k>0.02)", "inside bid-ask"], rows)
w("Mean error sign: positive = model IV above market.\n")

w("## 8. Multi-start behaviour (unconstrained)\n")
rows = []
for i, (x0, xh, cost, nfev, ok) in enumerate(sorted(res_free.starts, key=lambda s: s[2])):
    rows.append([i + 1] + [f"{v:.4f}" for v in xh] + [f"{np.sqrt(2 * cost / len(train)) * 100:.3f}", nfev])
table(["rank"] + list(NAMES) + ["approx IV RMSE", "iterations (residual evals, excl. Jacobian)"], rows)
costs = np.array([s[2] for s in res_free.starts])
near = np.sum(costs <= costs.min() * 1.01)
w(f"{near} of {len(costs)} starts end within 1% of the best objective value.\n")

# figures: smiles
exps = quotes.drop_duplicates("expiry").expiry.tolist()
pick = [exps[i] for i in np.linspace(0, len(exps) - 1, 9).round().astype(int)]
fig, axes = plt.subplots(3, 3, figsize=(13, 10))
for ax, e in zip(axes.ravel(), pick):
    d = allfit[allfit.expiry == e]
    ax.fill_between(d.k, d.iv_bid * 100, d.iv_ask * 100, color="0.85", label="bid-ask IV")
    ax.plot(d.k, d.iv * 100, ".", ms=3, color="k", label="market mid IV")
    T = d["T"].iloc[0]
    kk = np.linspace(d.k.min(), d.k.max(), 80)
    K = d.F.iloc[0] * np.exp(kk)
    kind = np.where(kk < 0, "put", "call")
    S_eff = d.S_eff.iloc[0]
    for res, c, lab in [(res_free, "C0", "Heston"), (res_fel, "C1", "Heston (Feller)"),
                        (res_eu, "C2", "Heston (de-Am. fit)")]:
        px = heston_price(S_eff, K, T, r, 0.0, res.params, kind)
        ax.plot(kk, implied_vol(px, S_eff, K, T, r, 0.0, kind) * 100, color=c, lw=1.4, label=lab)
    ax.set_title(f"{e} (T = {T * 365:.0f} d)", fontsize=9)
    ax.set_xlabel("ln(K/F)", fontsize=8)
    ax.set_ylabel("IV (%)", fontsize=8)
axes[0, 0].legend(fontsize=7)
fig.tight_layout()
fig.savefig(FIG / "phase3_smiles.png", dpi=140)
plt.close(fig)

fig, ax = plt.subplots(figsize=(9, 4.5))
sc = ax.scatter(allfit.k, allfit["T"], c=allfit.iv_err * 100, cmap="coolwarm", vmin=-3, vmax=3, s=8)
plt.colorbar(sc, label="model IV - market IV (vol points)")
ax.set_yscale("log")
ax.set_xlabel("ln(K/F)")
ax.set_ylabel("T (years, log scale)")
ax.set_title("Calibration residuals, unconstrained Heston")
fig.tight_layout()
fig.savefig(FIG / "phase3_residuals.png", dpi=140)
plt.close(fig)

w("## 9. Figures\n")
w("Market smiles with bid-ask band and the two calibrated models (9 of the expiries):\n")
w("![smiles](figures/phase3_smiles.png)\n")
w("Residual map (colour = model minus market IV, clipped at +-3 vol points):\n")
w("![residuals](figures/phase3_residuals.png)\n")

w("## 10. Caveats\n")
w("* One snapshot on a sharp down day; parameter stability over time is not tested.\n"
  "* Flat discount rate from ^IRX for all maturities (no Treasury curve available here).\n"
  "* Early-exercise premium handled by a first-order de-Americanisation with a flat r and a continuous q; the raw-quote fit ignores it (section 4).\n"
  "* End-of-day quotes from a free source; quote times differ by up to ~15 minutes across strikes.\n"
  "* A few quotes are clearly bad (e.g. isolated put IVs 10-15 points below their neighbours on 2027-03-31); they "
  "pass the filters, are kept, and account for the largest absolute errors. A robust loss (soft-L1) would reduce "
  "their influence.\n"
  "* At the ATM boundary of long maturities the put IVs sit above the call IVs (visible on 2029-01-19); this is the "
  "early-exercise premium of section 4 and is what the de-Americanised fit removes.\n")

out = {"asof": str(asof), "r": r, "spot_after_hours": spot_ah,
       "unconstrained": res_free.params.as_dict(), "feller_constrained": res_fel.params.as_dict(),
       "de_americanised": res_eu.params.as_dict()}
(OUT / "phase3_params.json").write_text(json.dumps(out, indent=1))
allfit.to_csv(OUT / "phase3_quotes.csv", index=False)
(OUT / "phase3_results.md").write_text("\n".join(lines))
print("\n".join(lines))
