"""Phase 5: Greeks and non-linear VaR / ES of three SPY option books under the calibrated Heston model.

Market state: the Phase 3 calibration (reports/phase3_params.json, unconstrained parameters) on the
2026-11-20 close; per-expiry dividend yield from the implied forwards (reports/phase3_quotes.csv).
Scenarios: historical SPY / VIX daily closes 2006-01-03 .. 2026-11-20 (data/history/).
Writes reports/phase5_results.md, reports/phase5_summary.json and figures. Every number is computed here.
Run:  python scripts/run_phase5.py   (a few minutes)
"""
from __future__ import annotations

import hashlib
import json
import platform
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from heston_risk import HestonParams, bs_price, heston_price, implied_vol  # noqa: E402
from heston_risk.risk.portfolio import Book, Market, Option, book_value, delta_hedge_shares, greeks  # noqa: E402
from heston_risk.risk.var import full_pnl, historical_scenarios, run_methods, var_es  # noqa: E402

OUT = ROOT / "reports"
FIG = OUT / "figures"
FIG.mkdir(parents=True, exist_ok=True)
lines: list[str] = []
w = lines.append
METHODS = ["delta", "delta_gamma", "dgv", "full", "full_nn"]
MLABEL = {"delta": "Delta (+theta)", "delta_gamma": "Delta-gamma", "dgv": "Delta-gamma-vega (+vanna, volga)",
          "full": "Full reval, analytic Heston", "full_nn": "Full reval, MLP surrogate"}


def table(header, rows):
    w("| " + " | ".join(header) + " |")
    w("|" + "---|" * len(header))
    for r in rows:
        w("| " + " | ".join(str(c) for c in r) + " |")
    w("")


def money(x):
    return f"{x:,.0f}"


# ---------------------------------------------------------------- market state
pr = json.load(open(OUT / "phase3_params.json"))
p = HestonParams(**pr["unconstrained"])
r, S0 = pr["r"], pr["spot_after_hours"]
m = Market(S=S0, v=p.v0, r=r, params=p)
quotes = pd.read_csv(OUT / "phase3_quotes.csv")
fw = quotes.groupby("expiry")[["T", "F"]].first()
raw = pd.read_csv(ROOT / "data" / "spy_2026-11-20" / "spy_options_raw.csv")


def expiry_info(expiry):
    T, F = float(fw.loc[expiry, "T"]), float(fw.loc[expiry, "F"])
    q = r - np.log(F / S0) / T
    strikes = np.sort(raw.loc[raw.expiry == expiry, "strike"].unique())
    return T, F, q, strikes


def nearest(strikes, x):
    return float(strikes[np.argmin(np.abs(strikes - x))])


E1, E3 = "2026-12-18", "2027-02-19"
T1, F1, q1, k1 = expiry_info(E1)
T3, F3, q3, k3 = expiry_info(E3)
K_atm = nearest(k1, F1)
K_otm = nearest(k3, 0.9 * F3)
N = 10  # contracts per leg

legs_A = (Option("call", K_atm, T1, q1, -N, f"short {N} {E1} {K_atm:.0f}C"),
          Option("put", K_atm, T1, q1, -N, f"short {N} {E1} {K_atm:.0f}P"),
          Option("put", K_otm, T3, q3, +N, f"long {N} {E3} {K_otm:.0f}P"))
book_A = Book(legs_A, delta_hedge_shares(Book(legs_A), m), "A: delta-hedged short straddle + protective put")
book_B = Book((Option("call", K_atm, T1, q1, +N, f"long {N} {E1} {K_atm:.0f}C"),), 0.0, "B: long ATM call")
book_C = Book((Option("put", K_atm, T1, q1, -N, f"short {N} {E1} {K_atm:.0f}P"),), 0.0, "C: naked short ATM put")
BOOKS = {"A": book_A, "B": book_B, "C": book_C}

# ---------------------------------------------------------------- scenarios
H = pd.read_csv(ROOT / "data" / "history" / "spy_vix_daily.csv", parse_dates=["date"])
meta_h = json.load(open(ROOT / "data" / "history" / "meta.json"))
sha = hashlib.sha256((ROOT / "data" / "history" / "spy_vix_daily.csv").read_bytes()).hexdigest()
assert sha == meta_h["sha256"]["spy_vix_daily.csv"], "history file changed"
spy, vix, dates = H.SPY.to_numpy(), H.VIX.to_numpy(), H.date.dt.strftime("%Y-%m-%d").to_numpy()

try:
    from heston_risk.surrogate.model import Surrogate
    sur = Surrogate.load(ROOT / "models" / "heston_iv_mlp.pt")
except ImportError as e:  # torch missing: run without the NN column
    print("surrogate unavailable:", e)
    sur = None

w("# Phase 5 results: Greeks and non-linear VaR / ES of SPY option books\n")
w(f"Generated by `scripts/run_phase5.py` (Python {platform.python_version()}, numpy {np.__version__}). "
  "Market state = Phase 3 calibration on the 2026-11-20 close; scenarios = daily SPY and VIX closes "
  f"{dates[0]} .. {dates[-1]} ({len(H):,} days, Yahoo Finance, sha256-verified).\n")

# ---------------------------------------------------------------- 1. setup
w("## 1. Market state and books\n")
table(["Item", "Value"], [
    ["Spot S (after-hours level implied by the 1-week forward)", f"{S0:.2f}"],
    ["Instantaneous variance v0 (sqrt = instantaneous vol)", f"{p.v0:.4f} ({np.sqrt(p.v0):.1%})"],
    ["kappa, theta, sigma, rho (held fixed)", f"{p.kappa:.3f}, {p.theta:.4f}, {p.sigma:.3f}, {p.rho:.3f}"],
    ["r (from ^IRX)", f"{r:.2%}"],
    [f"1M expiry {E1}: T, forward, implied q", f"{T1*365:.1f} days, {F1:.2f}, {q1:.2%}"],
    [f"3M expiry {E3}: T, forward, implied q", f"{T3*365:.1f} days, {F3:.2f}, {q3:.2%}"],
    ["ATM strike (listed strike nearest the 1M forward)", f"{K_atm:.0f}"],
    ["10% OTM put strike (listed strike nearest 0.9 x 3M forward)", f"{K_otm:.0f}"],
    ["Contract multiplier", "100 shares"],
    ["VIX on 2026-11-20", f"{vix[-1]:.2f}"],
])
rows = []
for key, b in BOOKS.items():
    legs = "; ".join(o.label for o in b.options)
    if b.shares:
        legs += f"; {b.shares:+,.0f} SPY shares (delta hedge)"
    rows.append([b.name, legs, money(book_value(b, m))])
table(["Book", "Positions", "Value today ($)"], rows)
w("Book A is the original design (sell short-dated volatility, hedge the delta with shares, buy a 3-month "
  "crash put). B and C are single unhedged options added for comparison: B is long gamma and long vega, "
  "C is short gamma and short vega.\n")

# ---------------------------------------------------------------- 2. Greeks
w("## 2. Greeks (finite differences on the analytic Heston pricer)\n")
w("Spot bump 0.1% of S, variance bump 1% of v0, one calendar day for theta; kappa, theta, sigma, rho fixed. "
  "Units: dollars of book value. Delta in $ per $1 of SPY (= share-equivalents), gamma in $ per $1^2, "
  "vega_v per unit of variance, vega per 1 vol point of sqrt(v0), theta per calendar day.\n")
G = {k: greeks(b, m) for k, b in BOOKS.items()}
table(["Book", "Delta", "Gamma", "Vega_v", "Vega / vol pt", "Vanna", "Volga", "Theta / day"],
      [[k, f"{g['delta']:,.1f}", f"{g['gamma']:,.2f}", f"{g['vega_v']:,.0f}", f"{g['vega_per_volpt']:,.0f}",
        f"{g['vanna']:,.1f}", f"{g['volga']:,.0f}", f"{g['theta']/365:,.0f}"] for k, g in G.items()])

# Heston delta vs Black-Scholes delta of the 1M ATM call (one share)
call1 = Option("call", K_atm, T1, q1, 1)
c_px = float(heston_price(S0, K_atm, T1, r, q1, p, "call"))
iv_atm = float(implied_vol(c_px, S0, K_atm, T1, r, q1, "call"))
h = 1e-3 * S0
bs_delta = (bs_price(S0 + h, K_atm, T1, r, q1, iv_atm, "call") - bs_price(S0 - h, K_atm, T1, r, q1, iv_atm, "call")) / (2 * h)
he_delta = greeks(Book((call1,)), m)["delta"] / 100
w(f"For reference, one {E1} {K_atm:.0f} call: Heston price {c_px:.2f}, implied vol {iv_atm:.1%}, "
  f"Heston delta (v held fixed) {he_delta:.3f} versus Black-Scholes delta at the same implied vol "
  f"{float(bs_delta):.3f}. The gap is the skew: with v fixed, a higher spot moves this strike toward the "
  "low-strike (high implied vol) side of the smile in moneyness terms, so the option gains extra value. "
  "This is the 'sticky moneyness' delta of a stochastic-vol model, not an error.\n")

# ---------------------------------------------------------------- 3. VaR / ES
w("## 3. VaR and ES by revaluation method\n")
w("Scenario for day t (horizon h trading days): SPY log return x = ln(S_{t+h}/S_t) and VIX ratio "
  "R = VIX_{t+h}/VIX_t, applied to today's state as S' = S e^x, v' = v0 R^2, with time to expiry reduced "
  "by h/252 years. 10-day scenarios are overlapping windows (not sqrt(10) scaled), so neighbouring "
  "scenarios share 9 days. VaR 99% and ES 97.5% are on loss = -P&L in dollars. Error = method minus full "
  "analytic revaluation, in % of the full-revaluation number.\n")

summary = {"books": {}, "asof": pr["asof"]}
pnl_store = {}
timing_rows = []
fallback_rows = []
for hd in (1, 10):
    x, R = historical_scenarios(spy, vix, hd)
    hy = hd / 252
    sd = dates[:-hd]
    w(f"### {hd}-day horizon ({len(x):,} scenarios)\n")
    for key, b in BOOKS.items():
        pnl, secs, _, fb = run_methods(b, m, x, R, hy, sur)
        pnl_store[(hd, key)] = (x, R, pnl, sd)
        ref_var, ref_es = var_es(pnl["full"])
        rows = []
        res = {}
        for meth in METHODS:
            if meth not in pnl:
                continue
            v_, e_ = var_es(pnl[meth])
            res[meth] = {"VaR99": v_, "ES975": e_}
            rows.append([MLABEL[meth], money(v_), f"{(v_ - ref_var) / abs(ref_var):+.1%}" if meth != "full" else "-",
                         money(e_), f"{(e_ - ref_es) / abs(ref_es):+.1%}" if meth != "full" else "-"])
        summary["books"].setdefault(key, {})[f"{hd}d"] = res
        w(f"**Book {b.name}**\n")
        table(["Method", "VaR 99% ($)", "VaR error", "ES 97.5% ($)", "ES error"], rows)
        timing_rows.append([f"{key}, {hd}d", *[f"{secs[mm]*1e3:,.1f}" if mm in secs else "-" for mm in METHODS]])
        if fb is not None:
            fallback_rows.append([f"{key}, {hd}d", f"{fb:,}", f"{len(x) * len(b.options):,}"])

# ---------------------------------------------------------------- 4. what drives the errors
w("## 4. Where the approximations fail\n")
w("Errors of each method against full analytic revaluation, scenario by scenario (1-day). "
  "'Small moves' = |SPY return| < 1% "
  f"({np.mean(np.abs(np.diff(np.log(spy))) < 0.01):.0%} of days); 'tail' = the 1% of days with the largest "
  "full-revaluation loss.\n")
rows = []
for key, b in BOOKS.items():
    x, R, pnl, sd = pnl_store[(1, key)]
    small = np.abs(x) < 0.01
    tail = -pnl["full"] >= np.quantile(-pnl["full"], 0.99)
    for meth in ("delta", "delta_gamma", "dgv", "full_nn"):
        if meth not in pnl:
            continue
        err = pnl[meth] - pnl["full"]
        rows.append([key, MLABEL[meth], money(np.sqrt(np.mean(err[small] ** 2))),
                     money(np.sqrt(np.mean(err[tail] ** 2))), money(np.mean(err[tail]))])
table(["Book", "Method", "RMS error, small moves ($)", "RMS error, tail ($)", "Mean error, tail ($)"], rows)
w("A positive mean tail error means the method shows a smaller loss than full revaluation (it understates "
  "risk); negative means it overstates the loss.\n")

w("Spot-only versus spot-and-vol scenarios (full analytic revaluation, 1-day): the same historical SPY "
  "returns with v0 held at today's level isolate how much of the risk comes from the volatility leg.\n")
rows = []
for key, b in BOOKS.items():
    x, R, pnl, sd = pnl_store[(1, key)]
    pnl_spot = full_pnl(b, m, S0 * np.exp(x), np.full(len(x), p.v0), 1 / 252)
    v1, e1 = var_es(pnl["full"])
    v2, e2 = var_es(pnl_spot)
    rows.append([key, money(v1), money(v2), money(e1), money(e2)])
table(["Book", "VaR 99%, spot + vol", "VaR 99%, spot only", "ES 97.5%, spot + vol", "ES 97.5%, spot only"], rows)

w("Worst five 1-day scenarios for each book (full analytic revaluation):\n")
rows = []
for key in BOOKS:
    x, R, pnl, sd = pnl_store[(1, key)]
    for i in np.argsort(pnl["full"])[:5]:
        rows.append([key, sd[i], f"{np.expm1(x[i]):+.2%}", f"{R[i]-1:+.1%}", money(pnl["full"][i]),
                     money(pnl["delta"][i]), money(pnl["delta_gamma"][i]), money(pnl["dgv"][i])])
table(["Book", "Start date", "SPY move", "VIX move", "Full P&L", "Delta", "Delta-gamma", "D-G-V"], rows)

# ---------------------------------------------------------------- 5. NN + timing
w("## 5. Surrogate domain and run time\n")
if fallback_rows:
    w("The MLP was trained on v0 <= 0.25, maturities >= 7 days and |ln(K/F)| <= 0.6 sqrt(T). Option "
      "evaluations outside that box are priced with the analytic formula instead (counted below), so the "
      "NN column is a hybrid in extreme scenarios.\n")
    table(["Book, horizon", "Fallback evaluations", "Total option evaluations"], fallback_rows)
w("Wall-clock time per method for all scenarios (milliseconds, single process). Taylor methods need the "
  "Greeks first (10 book valuations, a few milliseconds, not included).\n")
table(["Book, horizon", *[MLABEL[mm] for mm in METHODS]], timing_rows)

# ---------------------------------------------------------------- figures
fig, axes = plt.subplots(1, 3, figsize=(15, 4.4))
for ax, key in zip(axes, BOOKS):
    x, R, pnl, sd = pnl_store[(1, key)]
    o = np.argsort(x)
    ax.scatter(100 * np.expm1(x), pnl["full"] / 1e3, s=4, c="k", alpha=0.35, label="Full reval (analytic)")
    for meth, c in (("delta", "tab:red"), ("delta_gamma", "tab:blue"), ("dgv", "tab:green")):
        ax.scatter(100 * np.expm1(x[o]), pnl[meth][o] / 1e3, s=2, c=c, alpha=0.35, label=MLABEL[meth])
    ax.axhline(0, c="grey", lw=0.5)
    ax.set_title(BOOKS[key].name, fontsize=9)
    ax.set_xlabel("1-day SPY move (%)")
    ax.set_ylabel("P&L ($ thousand)")
axes[0].legend(fontsize=7, markerscale=4)
fig.tight_layout()
fig.savefig(FIG / "phase5_pnl_vs_spot.png", dpi=130)
w("![1-day P&L against the SPY move](figures/phase5_pnl_vs_spot.png)\n")

fig, axes = plt.subplots(1, 2, figsize=(11, 4))
for ax, hd in zip(axes, ("1d", "10d")):
    xs = np.arange(len(BOOKS))
    for j, meth in enumerate(("delta", "delta_gamma", "dgv", "full_nn")):
        if sur is None and meth == "full_nn":
            continue
        err = [100 * (summary["books"][k][hd][meth]["VaR99"] / summary["books"][k][hd]["full"]["VaR99"] - 1)
               for k in BOOKS]
        ax.bar(xs + 0.2 * (j - 1.5), err, width=0.2, label=MLABEL[meth])
    ax.axhline(0, c="k", lw=0.6)
    ax.set_xticks(xs, list(BOOKS))
    ax.set_title(f"VaR 99% error vs full revaluation, {hd}")
    ax.set_ylabel("%")
axes[0].legend(fontsize=7)
fig.tight_layout()
fig.savefig(FIG / "phase5_var_errors.png", dpi=130)
w("![VaR error by method](figures/phase5_var_errors.png)\n")

# ---------------------------------------------------------------- caveats
ee = quotes[((quotes.expiry == E1) & (quotes.strike == K_atm)) | ((quotes.expiry == E3) & (quotes.strike == K_otm))]
ee_note = ", ".join(f"{rw.expiry} {rw.strike:.0f}{rw.kind[0].upper()}: {rw.ee_premium_vol*100:.2f} vol pts"
                    for rw in ee.itertuples())
w("## 6. Assumptions and limits\n")
for s in [
    "Scenarios are real-world (historical) moves; prices are risk-neutral Heston values. This is standard "
    "historical-simulation practice, but the model's kappa, theta, sigma, rho are held at their 2026-11-20 "
    "calibration ('sticky parameters'): in reality the whole surface would be re-fitted after a shock.",
    "VIX is a 30-day implied vol, not sqrt(v0); mapping v' = v0 (VIX'/VIX)^2 assumes the instantaneous "
    "variance moves in proportion to VIX squared.",
    "Relative VIX moves are applied to a high starting level (VIX 35.9 today). Historical calm-period "
    "changes may understate how violently vol moves from a stressed level, and vice versa.",
    "SPY prices are unadjusted closes, so the roughly quarterly ex-dividend drops (about 0.3-0.5%) appear "
    "as small negative returns. Their effect on 99% VaR is small but not zero.",
    "There is no backtest: we do not have historical option prices for these exact books, so the VaR is "
    "validated only against full revaluation inside the model, not against realised option P&L.",
    "American early exercise is ignored (European pricing). Phase 3's CRR estimate of the early-exercise "
    f"premium is {ee_note} for the options used here.",
]:
    w(f"- {s}")
w("")

(OUT / "phase5_results.md").write_text("\n".join(lines))
json.dump(summary, open(OUT / "phase5_summary.json", "w"), indent=1)
print("\n".join(lines))
