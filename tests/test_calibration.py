import json
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from heston_risk import HestonParams, bs_price, heston_price
from heston_risk.bs import bs_vega
from heston_risk.calibration.american import crr_price, de_americanize, early_exercise_premium
from heston_risk.calibration.calibrate import calibrate, fit_report
from heston_risk.calibration.data import (QuoteFilter, build_quotes, implied_forwards, load_snapshot,
                                          rate_from_irx, year_fractions)

R = 0.04
ASOF = pd.Timestamp("2026-01-02 21:00", tz="UTC")


def test_rate_from_irx_bank_discount_conversion():
    # P = 1 - 0.04 * 91/360 ; r = -ln P / (91/365)
    P = 1 - 0.04 * 91 / 360
    assert rate_from_irx(4.0) == pytest.approx(-np.log(P) / (91 / 365))
    assert rate_from_irx(4.0) > 0.04  # discount yield understates the continuous rate


def test_year_fraction_to_4pm_new_york():
    T = year_fractions(pd.Series(["2026-01-09"]), ASOF).iloc[0]
    assert T == pytest.approx(7 / 365)


def _synthetic_chain(p: HestonParams, S=100.0, q=0.01, expiries=("2026-02-20", "2026-06-19", "2027-01-15")):
    rows = []
    for e in expiries:
        T = float(year_fractions(pd.Series([e]), ASOF).iloc[0])
        for K in np.arange(70, 131, 2.5):
            for kind in ("call", "put"):
                px = float(heston_price(S, K, T, R, q, p, kind))
                rows.append(dict(expiry=e, strike=K, kind=kind, bid=px * 0.995, ask=px * 1.005,
                                 lastTradeDate=ASOF, volume=10, openInterest=100, impliedVolatility=np.nan))
    return pd.DataFrame(rows)


def test_implied_forward_recovers_true_forward():
    p = HestonParams(0.04, 2.0, 0.04, 0.5, -0.7)
    raw = _synthetic_chain(p)
    fwd = implied_forwards(raw, R, ASOF, spot_ref=100.0)
    true_F = 100 * np.exp((R - 0.01) * fwd["T"])
    assert np.allclose(fwd.F, true_F, atol=1e-8)


def test_build_quotes_keeps_only_otm_and_valid():
    p = HestonParams(0.04, 2.0, 0.04, 0.5, -0.7)
    raw = _synthetic_chain(p)
    raw.loc[0, ["bid", "ask"]] = [0.0, 0.0]
    fwd = implied_forwards(raw, R, ASOF, spot_ref=100.0)
    q, funnel = build_quotes(raw, fwd, R, QuoteFilter(min_days=7))
    assert np.all(((q.kind == "put") & (q.strike < q.F)) | ((q.kind == "call") & (q.strike >= q.F)))
    assert np.all(np.isfinite(q.iv)) and np.all(q.vega > 0)
    assert list(funnel.rows) == sorted(funnel.rows, reverse=True)


def test_calibration_recovers_known_parameters():
    """Prices generated by Heston with known parameters -> calibration returns them."""
    true = HestonParams(0.05, 2.5, 0.045, 0.6, -0.65)
    raw = _synthetic_chain(true)
    fwd = implied_forwards(raw, R, ASOF, spot_ref=100.0)
    q, _ = build_quotes(raw, fwd, R, QuoteFilter(min_days=7, moneyness_width=1.0))
    res = calibrate(q, R, n_starts=3, seed=1)
    est = res.params
    assert res.rmse_vega_weighted < 1e-6
    for name in ("v0", "kappa", "theta", "sigma", "rho"):
        assert getattr(est, name) == pytest.approx(getattr(true, name), rel=1e-3)
    rep = fit_report(q, est, R)
    assert np.nanmax(np.abs(rep.iv_err)) < 1e-6


def test_feller_constrained_calibration_respects_feller():
    true = HestonParams(0.05, 2.5, 0.045, 0.9, -0.65)  # violates Feller (ratio 0.28)
    raw = _synthetic_chain(true)
    fwd = implied_forwards(raw, R, ASOF, spot_ref=100.0)
    q, _ = build_quotes(raw, fwd, R)
    res = calibrate(q, R, n_starts=2, seed=1, feller=True)
    assert res.params.feller_ratio >= 1 - 1e-9


def test_crr_converges_to_black_scholes_for_european():
    assert crr_price(100, 95, 1.0, 0.03, 0.01, 0.25, "put", american=False, n=2000) == pytest.approx(
        float(bs_price(100, 95, 1.0, 0.03, 0.01, 0.25, "put")), abs=5e-3)


def test_early_exercise_premium_signs():
    prem_put, _ = early_exercise_premium(100, 110, 2.0, 0.05, 0.0, 0.2, "put")
    prem_call, _ = early_exercise_premium(100, 110, 2.0, 0.05, 0.0, 0.2, "call")
    assert prem_put > 0.05          # r > 0: American put worth more
    assert abs(prem_call) < 1e-10   # no dividends: never exercise a call early


def test_de_americanize_round_trip():
    S, K, T, r, q, s = 100.0, 105.0, 1.5, 0.045, 0.01, 0.22
    am = crr_price(S, K, T, r, q, s, "put", True, 300)
    eu_equiv, sA = de_americanize(am, S, K, T, r, q, "put", 0.25, n=300)
    assert sA == pytest.approx(s, abs=1e-6)
    assert eu_equiv == pytest.approx(float(bs_price(S, K, T, r, q, s, "put")), abs=0.02)


def test_snapshot_integrity_check(tmp_path):
    (tmp_path / "spy_options_raw.csv").write_text("a\n1\n")
    (tmp_path / "irx_10d.csv").write_text("Close\n4\n")
    (tmp_path / "spy_history_10d.csv").write_text("Close\n1\n")
    meta = {"sha256": {"spy_options_raw.csv": "0" * 64}}
    (tmp_path / "meta.json").write_text(json.dumps(meta))
    with pytest.raises(ValueError):
        load_snapshot(tmp_path)


